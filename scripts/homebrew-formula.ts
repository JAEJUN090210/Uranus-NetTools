import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

import pkg from '../package.json' with { type: 'json' };

// 사용법: tsx scripts/homebrew-formula.ts [--base-url <주소>]
// dist/release의 macOS·Linux 압축 파일로 Homebrew formula(dist/homebrew/unt.rb)를 만듭니다.
// 주소를 주지 않으면 이 버전의 GitHub Release 주소를 씁니다. PR에서는 file:// 주소로 실제 설치를 시험합니다.

const ROOT = resolve(import.meta.dirname, '..');
const RELEASE = join(ROOT, 'dist', 'release');
const OUTPUT = join(ROOT, 'dist', 'homebrew', 'unt.rb');
const HOMEPAGE = 'https://github.com/JAEJUN090210/Uranus-NetTools';

const { values } = parseArgs({ options: { 'base-url': { type: 'string' } } });
const baseUrl = values['base-url'] ?? `${HOMEPAGE}/releases/download/v${pkg.version}`;
// Homebrew는 GitHub Release 주소의 /download/v<버전>/에서 버전을 읽으므로 보통은 version 줄이 필요 없고,
// 있으면 audit이 중복이라고 막습니다. 다른 주소를 쓰면 파일 이름의 arm64에서 64를 버전으로 읽어서 직접 적습니다.
const versionLine = values['base-url'] === undefined ? '' : `  version "${pkg.version}"\n`;

/** 운영체제·CPU별로 받을 압축 파일의 주소와 체크섬입니다. */
function archive(target: string): { url: string; sha256: string } {
  const file = `unt-${pkg.version}-${target}.tar.gz`;
  const path = join(RELEASE, file);
  if (!existsSync(path)) {
    throw new Error(`${file} is missing from dist/release`);
  }
  return {
    url: `${baseUrl}/${file}`,
    sha256: createHash('sha256').update(readFileSync(path)).digest('hex'),
  };
}

function block(os: 'macos' | 'linux', indent: string): string {
  return [
    ['arm', 'arm64'],
    ['intel', 'x64'],
  ]
    .map(([cpu, arch]) => {
      const { url, sha256 } = archive(`${os}-${arch}`);
      return [
        `${indent}on_${cpu} do`,
        `${indent}  url "${url}"`,
        `${indent}  sha256 "${sha256}"`,
        `${indent}end`,
      ].join('\n');
    })
    .join('\n');
}

const formula = `# Generated by the Uranus-NetTools release workflow. Do not edit by hand.
class Unt < Formula
  desc "Cross-platform command-line network toolkit"
  homepage "${HOMEPAGE}"
${versionLine}  license "GPL-3.0-or-later"

  on_macos do
${block('macos', '    ')}
  end

  on_linux do
${block('linux', '    ')}
  end

  def install
    bin.install "unt"
    doc.install "THIRD-PARTY-NOTICES.txt"
  end

  test do
    assert_equal version.to_s, shell_output("#{bin}/unt --version").strip
  end
end
`;

mkdirSync(join(ROOT, 'dist', 'homebrew'), { recursive: true });
writeFileSync(OUTPUT, formula);
console.log(`${OUTPUT} (${baseUrl})`);
